'use server';

/**
 * @fileOverview This file defines a Genkit flow for generating minimal pair targets based on a given phonological error.
 *
 * - generateMinimalPairTargets - A function that generates minimal pair targets.
 * - MinimalPairInput - The input type for the generateMinimalPairTargets function.
 * - MinimalPairOutput - The return type for the generateMinimalPairTargets function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

const MinimalPairInputSchema = z.object({
  phonologicalError: z
    .string()
    .describe("The child's phonological error (e.g., 'substitution of /t/ for /k/')"),
  stimulableSounds: z.array(z.string()).optional().describe('A list of sounds the child can produce with stimulation.'),
  phoneticInventory: z.array(z.string()).optional().describe('A list of sounds the child can produce spontaneously.'),
  syllableLength: z.string().optional().describe('The desired syllable length for the target words (e.g., "one syllable", "two syllables").'),
  phonemePosition: z.string().optional().describe('The desired position of the target sound in the word (e.g., "initial", "medial", "final").'),
});
export type MinimalPairInput = z.infer<typeof MinimalPairInputSchema>;

const MinimalPairOutputSchema = z.object({
  minimalPairTargets: z
    .array(
      z.object({
        pair: z.string().describe('The minimal word pair, separated by a hyphen.'),
        rationale: z.string().describe('A brief explanation of why this pair was chosen, including the source for the logic.'),
      })
    )
    .describe('A list of minimal pair targets generated by the AI model.'),
});
export type MinimalPairOutput = z.infer<typeof MinimalPairOutputSchema>;

export async function generateMinimalPairTargets(
  input: MinimalPairInput
): Promise<MinimalPairOutput> {
  return generateMinimalPairTargetsFlow(input);
}

const prompt = ai.definePrompt({
  name: 'minimalPairPrompt',
  input: {schema: MinimalPairInputSchema},
  output: {schema: MinimalPairOutputSchema},
  prompt: `You are a speech language pathologist expert in phonological interventions.

  Given the following phonological error, generate a list of 5 minimal pair targets that would be appropriate for therapy.
  Minimal pairs contrast two words that differ by only a single sound, highlighting the semantic difference that the sound makes.

  Phonological Error: {{{phonologicalError}}}

  {{#if syllableLength}}
  The generated words should have {{syllableLength}}.
  {{/if}}

  {{#if phonemePosition}}
  The target sounds should be in the {{phonemePosition}} position of the word.
  {{/if}}

  {{#if phoneticInventory}}
  The child's phonetic inventory (sounds they can produce) includes: {{phoneticInventory}}.
  {{/if}}

  {{#if stimulableSounds}}
  The child is stimulable for the following sounds: {{stimulableSounds}}.
  {{/if}}

  When generating targets, consider the child's phonetic inventory and stimulability.
  For minimal pairs, you may want to select targets that are just outside their current abilities.

  For each pair, provide a brief 'rationale' explaining why it's a good choice and cite the source of the logic. For example: "This pair contrasts /t/ and /k/ to address the process of fronting, based on the Minimal Pairs approach by Weiner (1981)."
  Format each target as an object with the word 'pair' (e.g., "tea - key") and the 'rationale'.
`,
});

const generateMinimalPairTargetsFlow = ai.defineFlow(
  {
    name: 'generateMinimalPairTargetsFlow',
    inputSchema: MinimalPairInputSchema,
    outputSchema: MinimalPairOutputSchema,
  },
  async input => {
    const {output} = await prompt(input);
    return output!;
  }
);
